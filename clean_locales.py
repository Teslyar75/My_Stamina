# Compile patterns
garbage_regexes = [re.compile(p) for p in GARBAGE_PATTERNS]

def is_garbage(key):
    """Check if a key matches any garbage pattern."""
    for regex in garbage_regexes:
        if regex.search(key):
            return True
    return False

# Clean each locale
for lang in locales:
    original_count = len(locales[lang])
    locales[lang] = {k: v for k, v in locales[lang].items() if not is_garbage(k)}
    removed = original_count - len(locales[lang])
    print(f"  {lang}: removed {removed} garbage keys, {len(locales[lang])} remaining")

# Save cleaned locale files
for lang in locales:
    with open(f'stamina/i18n/{lang}.json', 'w', encoding='utf-8') as f:
        json.dump(locales[lang], f, ensure_ascii=False, indent=2, sort_keys=True)

print("\nDone cleaning locale files.")