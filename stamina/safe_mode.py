"""Безопасный запуск: минимум подсистем, если корабль ведёт себя странно.

Зачем: когда окно не отвечает, что-то гудит на 100 % ядра или скин ломает вид,
пилоту нужен способ войти и всё починить. В безопасном режиме борт не запускает
живой космос, звук, оверлей отдыха и фоновую сборку тяжёлых отсеков, не лезет в
сеть и не опрашивает обновления. Данные и файлы не трогаются — только тишина.

Включается ключом ``--safe`` (или переменной окружения ``STAR_TYPING_SAFE=1``).
"""
from __future__ import annotations

import os

ENV = "STAR_TYPING_SAFE"
FLAG = "--safe"

_TRUE = ("1", "true", "yes", "on", "да")


def enabled() -> bool:
    """Запущен ли борт в безопасном режиме прямо сейчас."""
    return os.environ.get(ENV, "").strip().lower() in _TRUE


def set_enabled(value: bool = True) -> None:
    """Включить (или выключить) безопасный режим для текущего процесса."""
    if value:
        os.environ[ENV] = "1"
    else:
        os.environ.pop(ENV, None)


def flag_in(argv) -> bool:
    """Есть ли ключ ``--safe`` среди аргументов командной строки."""
    return any(str(a).strip().lower() == FLAG for a in (argv or ()))


def notice() -> str:
    """Строка для журнала и статуса — что именно отключено."""
    return ("безопасный режим: без живого космоса, звука, отдыха, "
            "сети и фоновой сборки отсеков")
