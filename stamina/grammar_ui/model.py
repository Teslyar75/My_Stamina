"""Общая модель вкладки грамматики: источники, модули, уроки."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Protocol


@dataclass(frozen=True)
class SourceTab:
    """Источник в переключателе вкладок. Список задаёт страница языка."""

    id: str
    title: str
    attribution: str = ""
    url: str = ""


@dataclass(frozen=True)
class ModuleItem:
    id: str
    title: str
    subtitle: str = ""


@dataclass(frozen=True)
class UnitItem:
    """Строка списка слева. id — устойчивый ключ урока/темы."""

    id: Any
    number: str
    title: str
    level: str = ""
    module_id: str = ""


class GrammarCatalog(Protocol):
    """Поставщик данных для GrammarSpread. Не читает уроки при импорте."""

    levels: list[str]
    show_source_tabs: bool

    def sources(self) -> list[SourceTab]: ...
    def select_source(self, source_id: str) -> None: ...
    def current_source_id(self) -> str: ...
    def load_index(self) -> None: ...
    def index_loaded(self) -> bool: ...
    def header_subtitle(self, level: str) -> str: ...
    def progress_text(self) -> str: ...
    def list_plan(self, level: str) -> list[tuple[str, Any]]: ...
    def first_unit(self, level: str) -> Any: ...
    def level_of(self, unit_id: Any) -> str: ...
    def load_lesson(self, unit_id: Any) -> dict: ...
    def neighbours(self, unit_id: Any) -> tuple[Any, Any]: ...
    def hint_for_unit(self, unit_id: Any) -> str: ...
    def unit_number(self, unit_id: Any) -> int: ...
    def is_done(self, unit_id: Any) -> bool: ...
    def mark_complete(self, unit_id: Any, ok: int, total: int) -> bool: ...
    def lesson_answers(self, ex: dict) -> list[str]: ...
    def gap_ok(self, value: str, ex: dict) -> bool: ...
    def choice_index(self, ex: dict) -> int: ...
