def topics() -> list[dict]:
    """Все темы учебника (для панели и тестов)."""
    return [dict(topic_item) for topic_item in TOPICS]


def topic(topic_id: str) -> dict | None:
    for item in TOPICS:
        if item["id"] == topic_id:
            return item
    return None


def commands(topic_id: str | None = None) -> list[dict]:
    """Клавиши одной темы или все подряд."""
    if topic_id is None:
        return [c for t in TOPICS for c in t["commands"]]
    item = topic(topic_id)
    return list(item["commands"]) if item else []


def total() -> int:
    return sum(len(t["commands"]) for t in TOPICS)


def supported() -> list[dict]:
    """Клавиши, которые тренажёр выполняет по-настоящему (``sim is True``)."""
    return [c for c in commands() if c.get("sim") is True]


def simplified() -> list[dict]:
    """Клавиши, которые движок понимает, но упрощённо."""
    return [c for c in commands() if c.get("sim") == "partial"]


def search(query: str, topic_id: str | None = None) -> list[dict]:
    """Поиск по учебнику: все слова запроса должны найтись в клавишах или описании.

    Пустой запрос — клавиши выбранной темы (или все).
    """
    q = (query or "").strip().lower()
    items = commands(topic_id)
    if not q:
        return items
    words = q.split()
    return [c for c in items if all(w in (c["cmd"] + " " + c["desc"]).lower() for w in words)]


def lessons() -> list[str]:
    """Уроки тренажёра, на которые ссылается учебник (без дублей, по порядку)."""
    out: list[str] = []
    for item in commands():
        lesson = item.get("lesson")
        if lesson and lesson not in out:
            out.append(lesson)
    return out
