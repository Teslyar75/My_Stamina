def _topic(topic_id, title, blurb, theory, rows):
    """Ряды ``(клавиша, описание)`` → формат тем ``vim_reference``."""
    return {
        "id": topic_id,
        "title": title,
        "blurb": blurb,
        "theory": list(theory),
        "commands": [
            {"cmd": cmd, "desc": desc, "example": cmd, "sim": False}
            for cmd, desc in rows
        ],
    }


