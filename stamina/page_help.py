def hotkeys_for(key: str) -> str:
    base = (key or "").split(".", 1)[0]
    zone = "bridge" if base in ("missions", "cargo", "log") else base
    local = HOTKEYS.get(base) or HOTKEYS.get(zone) or ""
    return _t("КЛАВИШИ") + "\n" + ("• " + _t(local) + "\n" if local else "") + "• " + _t(GLOBAL_KEYS)


def siblings(key: str) -> list[str]:
    """Темы того же раздела (Tab в окне справки листает их)."""
    base = (key or "").split(".", 1)[0]
    out = [k for k in PAGES if k == base or k.startswith(base + ".")]
    return out or [key]


def resolve_key(app) -> str:
    """Ключ справки по текущему экрану и подразделу."""
    cur = getattr(app, "current", None) or "bridge"
    if cur == "help":
        return "help"
    scr = (getattr(app, "screens", None) or {}).get(cur)
    if scr is not None and hasattr(scr, "page_help_key"):
        try:
            key = scr.page_help_key()
            if key:
                return str(key)
        except Exception:  # noqa: BLE001
            pass
    sub = getattr(scr, "current", None) if scr is not None else None
    if sub:
        compound = f"{cur}.{sub}"
        if compound in PAGES:
            return compound
    return cur if cur in PAGES else "bridge"


def content_for(key: str) -> tuple[str, str]:
    if key in PAGES:
        return PAGES[key]
    if "." in key:
        base = key.split(".", 1)[0]
        if base in PAGES:
            return PAGES[base]
    return PAGES["bridge"]


class PageHelpDialog(tk.Toplevel):
    """Модальное окно: как работает текущая страница."""

    def __init__(self, app, key: str | None = None) -> None:
        super().__init__(app)
        self.app = app
        self.key = key or resolve_key(app)
        title, body = content_for(self.key)
        self.title(_t("Справка · {0}").format(title))
        self.configure(bg=BG)
        self.transient(app)
        self.resizable(True, True)
        self.minsize(px(420), px(280))
        sw, sh = monitors.area_size(app)          # монитор окна программы, не основной
        w, h = min(px(680), int(sw * 0.9)), min(px(560), int(sh * 0.85))
        self.geometry(monitors.center_geometry(app, w, h))

        head = tk.Frame(self, bg=BG)
        head.pack(fill=tk.X, padx=px(16), pady=(px(14), px(6)))
