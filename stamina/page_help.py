def hotkeys_for(key: str) -> str:
    base = (key or "").split(".", 1)[0]
    zone = "bridge" if base in ("missions", "cargo", "log") else base
    local = HOTKEYS.get(base) or HOTKEYS.get(zone) or ""
    return _t("КЛАВИШИ") + "\n" + ("• " + _t(local) + "\n" if local else "") + "• " + _t(GLOBAL_KEYS)


def siblings(key: str) -> list[str]:
    """Темы того же раздела (Tab в окне справки листает их)."""
    base = (key or "").split(".", 1)[0]
    out = [k for k in PAGES if k == base or k.startswith(base + ".")]
    return out or [key]


def resolve_key(app) -> str:
    """Ключ справки по текущему экрану и подразделу."""
    cur = getattr(app, "current", None) or "bridge"
    if cur == "help":
        return "help"
    scr = (getattr(app, "screens", None) or {}).get(cur)
    if scr is not None and hasattr(scr, "page_help_key"):
        try:
            key = scr.page_help_key()
            if key:
                return str(key)
        except Exception:  # noqa: BLE001
            pass
    sub = getattr(scr, "current", None) if scr is not None else None
    if sub:
        compound = f"{cur}.{sub}"
        if compound in PAGES:
            return compound
    return cur if cur in PAGES else "bridge"


def content_for(key: str) -> tuple[str, str]:
    if key in PAGES:
        return PAGES[key]
    if "." in key:
        base = key.split(".", 1)[0]
        if base in PAGES:
            return PAGES[base]
    return PAGES["bridge"]


class PageHelpDialog(tk.Toplevel):
    """Модальное окно: как работает текущая страница."""

    def __init__(self, app, key: str | None = None) -> None:
        super().__init__(app)
        self.app = app
        self.key = key or resolve_key(app)
        title, body = content_for(self.key)
        self.title(_t("Справка · {0}").format(title))
        self.configure(bg=BG)
        self.transient(app)
        self.resizable(True, True)
        self.minsize(px(420), px(280))
        sw, sh = monitors.area_size(app)          # монитор окна программы, не основной
        w, h = min(px(680), int(sw * 0.9)), min(px(560), int(sh * 0.85))
        self.geometry(monitors.center_geometry(app, w, h))

        head = tk.Frame(self, bg=BG)
        head.pack(fill=tk.X, padx=px(16), pady=(px(14), px(6)))
        tk.Label(head, text="?", bg=BG, fg=AMBER, font=theme.font(18, True)).pack(side=tk.LEFT, padx=(0, px(10)))
        tk.Label(head, text=title, bg=BG, fg=TEXT, font=theme.font(14, True)).pack(side=tk.LEFT)
        tk.Label(head, text=_t("как работает эта страница"), bg=BG, fg=MUTED,
                 font=theme.font(9)).pack(side=tk.LEFT, padx=px(12))

        tk.Frame(self, bg=LINE, height=1).pack(fill=tk.X, padx=px(16))

        box = tk.Frame(self, bg=BG2, highlightthickness=1, highlightbackground=LINE)
        box.pack(fill=tk.BOTH, expand=True, padx=px(16), pady=px(10))
        style = ttk.Style(self)
        try:
            style.theme_use("clam")
        except tk.TclError:
            pass
        style.configure("Hud.Vertical.TScrollbar", background=PANEL_HI, troughcolor=BG2,
                        bordercolor=PANEL, arrowcolor=CYAN, lightcolor=PANEL_HI, darkcolor=PANEL_HI)
        sb = ttk.Scrollbar(box, orient=tk.VERTICAL, style="Hud.Vertical.TScrollbar")
        sb.pack(side=tk.RIGHT, fill=tk.Y)
        t = tk.Text(box, wrap=tk.WORD, bg=BG2, fg=TEXT, relief=tk.FLAT, padx=px(14), pady=px(12),
                    yscrollcommand=sb.set, font=theme.font(11), highlightthickness=0,
                    spacing1=px(2), spacing3=px(3))
        t.pack(fill=tk.BOTH, expand=True)
        sb.configure(command=t.yview)
        self.text = t
        self.head_title = head.winfo_children()[1]
        self._fill(self.key)

        foot = tk.Frame(self, bg=BG)
        foot.pack(fill=tk.X, padx=px(16), pady=(0, px(12)))
        HudButton(foot, _t("ПОЛНАЯ ИНСТРУКЦИЯ"), self._full_help, height=32, font_size=9,
                  color=CYAN).pack(side=tk.LEFT)
        HudButton(foot, _t("ЗАКРЫТЬ  Esc"), self.destroy, height=32, font_size=9,
                  color=AMBER).pack(side=tk.RIGHT)

        self.bind("<Escape>", lambda _e: self.destroy())
        self.bind("<F1>", lambda _e: self.destroy())
        # клавиатура: стрелки / PgUp PgDn / Home End — прокрутка, Tab / Shift+Tab — соседние темы раздела
        for seq, cmd in (("<Up>", lambda: t.yview_scroll(-2, "units")), ("<Down>", lambda: t.yview_scroll(2, "units")),
                         ("<Prior>", lambda: t.yview_scroll(-1, "pages")), ("<Next>", lambda: t.yview_scroll(1, "pages")),
                         ("<Home>", lambda: t.yview_moveto(0)), ("<End>", lambda: t.yview_moveto(1))):
            self.bind(seq, lambda _e, c=cmd: (c(), "break")[1])
        self.bind("<Tab>", lambda _e: (self.next_topic(1), "break")[1])
        for seq in ("<Shift-Tab>", "<ISO_Left_Tab>"):
            try:
                self.bind(seq, lambda _e: (self.next_topic(-1), "break")[1])
            except tk.TclError:
                pass
        self.protocol("WM_DELETE_WINDOW", self.destroy)
        self.grab_set()
        self.focus_set()

    def _fill(self, key: str) -> None:
        self.key = key
        title, body = content_for(key)
        self.title(_t("Справка · {0}").format(title))
        self.head_title.configure(text=title)
        topics = siblings(key)
        nav_line = ""
        if len(topics) > 1:
            nav_line = "\n\n" + _t("Tab / Shift+Tab — другие темы раздела ({0} из {1})").format(
                topics.index(key) + 1 if key in topics else 1, len(topics))
        t = self.text
        t.configure(state=tk.NORMAL)
        t.delete("1.0", tk.END)
        t.insert("1.0", body + "\n\n" + hotkeys_for(key) + nav_line)
        t.configure(state=tk.DISABLED)
        t.yview_moveto(0)

    def next_topic(self, step: int) -> None:
        topics = siblings(self.key)
        if len(topics) < 2:
            return
        i = topics.index(self.key) if self.key in topics else 0
        self._fill(topics[(i + step) % len(topics)])

    def _full_help(self) -> None:
        self.destroy()
        self.app.show("help")
        scr = self.app.screens.get("help")
        if scr is not None and hasattr(scr, "goto"):
            base = (self.key or "").split(".", 1)[0]
            chapter = {
                "english": _t("АНГЛИЙСКИЙ"),
                "speedread": _t("СКОРОЧТЕНИЕ"),
                "lounge": _t("ОТДЫХ"),
                "radio": _t("РАДИОРУБКА"),
                "honor": _t("ЭКИПАЖ"),
                "bridge": _t("МОСТИК"),
                "missions": _t("МИССИИ"),
                "cargo": _t("СВОЙ ТЕКСТ"),
                "comm": _t("ЭФИР"),
                "orion": _t("ОРИОН"),
            }.get(base)
            scr.goto(chapter)


def open_page_help(app, key: str | None = None) -> None:
    """Показать модалку; повторный F1 закрывает предыдущую."""
    prev = getattr(app, "_page_help_dlg", None)
    if prev is not None:
        try:
            if prev.winfo_exists():
                prev.destroy()
        except tk.TclError:
            pass
    dlg = PageHelpDialog(app, key)
    app._page_help_dlg = dlg
